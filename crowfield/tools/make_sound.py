#!/usr/bin/env python3
"""sound/*.wav (mono 16-bit, from tools/import_sound.sh) -> src/sound.h (signed 8-bit at the GBA mix rate).

Each clip is resampled to RATE, trimmed of silence at both ends, normalized to its PEAK, and faded out.
The order of SOUNDS is the SND_* enum in main.c.
--preview DIR also writes DIR/<name>.wav: the exact 8-bit samples the GBA plays, to listen to.
Python standard library only, so the build needs no ffmpeg.
"""
import os, sys, wave, struct

RATE = 13379          # 224 samples per frame: 280896 cycles / 1254 cycles per sample (timer 0)
SOUNDS = [            # name, peak (of 127): loudness relative to the others
    ("swing", 70),
    ("hit", 110),
    ("caw", 110),
    ("hurt", 120),
    ("plant", 80),
    ("harvest", 90),
    ("noseeds", 80),
]
ROOT = os.path.join(os.path.dirname(__file__), "..")


def read_wav(path):
    with wave.open(path, "rb") as w:
        assert w.getnchannels() == 1 and w.getsampwidth() == 2, path + ": run tools/import_sound.sh"
        rate = w.getframerate()
        raw = w.readframes(w.getnframes())
    return [s / 32768.0 for s in struct.unpack("<%dh" % (len(raw) // 2), raw)], rate


def resample(x, src, dst):   # linear interpolation
    n = int(len(x) * dst / src)
    out = []
    for i in range(n):
        p = i * src / dst
        j = int(p)
        f = p - j
        a = x[j]
        b = x[j + 1] if j + 1 < len(x) else a
        out.append(a + (b - a) * f)
    return out


def convert(name, peak):
    x, rate = read_wav(os.path.join(ROOT, "sound", name + ".wav"))
    x = resample(x, rate, RATE)
    top = max(abs(s) for s in x) or 1.0
    quiet = top * 0.02
    a = next(i for i, s in enumerate(x) if abs(s) > quiet)
    b = len(x) - next(i for i, s in enumerate(reversed(x)) if abs(s) > quiet)
    x = x[a:b]
    fade = min(len(x), RATE // 100)   # 10 ms fade-out, so a clip never ends in a click
    for i in range(fade):
        x[len(x) - fade + i] *= (fade - i) / fade
    return [max(-128, min(127, round(s / top * peak))) for s in x]


def main():
    clips = [(name, convert(name, peak)) for name, peak in SOUNDS]
    lines = ["// GENERATED by tools/make_sound.py from sound/*.wav. Do not edit.",
             "#define SND_RATE %d" % RATE, ""]
    for name, s in clips:
        lines.append("static const signed char snd_%s[%d] = {" % (name, len(s)))
        for i in range(0, len(s), 24):
            lines.append("    " + ",".join(str(v) for v in s[i:i + 24]) + ",")
        lines.append("};")
    lines.append("static const signed char *const snd_data[] = { %s };" % ", ".join("snd_" + n for n, _ in clips))
    lines.append("static const unsigned short snd_len[] = { %s };" % ", ".join(str(len(s)) for _, s in clips))
    with open(os.path.join(ROOT, "src", "sound.h"), "w") as f:
        f.write("\n".join(lines) + "\n")
    total = sum(len(s) for _, s in clips)
    print("wrote src/sound.h: %d clips, %d bytes" % (len(clips), total))

    if "--preview" in sys.argv:
        out = sys.argv[sys.argv.index("--preview") + 1]
        os.makedirs(out, exist_ok=True)
        for name, s in clips:
            with wave.open(os.path.join(out, name + ".wav"), "wb") as w:
                w.setnchannels(1); w.setsampwidth(1); w.setframerate(RATE)
                w.writeframes(bytes((v + 128) & 255 for v in s))   # 8-bit WAV is unsigned
            print("  %-8s %.2f s" % (name, len(s) / RATE))


if __name__ == "__main__":
    main()
